package org.boxinggod.boxing_god_bot.service;

import org.boxinggod.boxing_god_bot.entity.CustomBoxer;
import org.springframework.ai.chat.client.ChatClient;
import org.springframework.stereotype.Service;

@Service
public class BoxingFightService {

    private final ChatClient chatClient;

    public BoxingFightService(ChatClient.Builder chatClientBuilder) {
        this.chatClient = chatClientBuilder.build();
    }

    public String simulateFight(String boxer1, String boxer2) {
        String systemPrompt = """
            Ты — ведущий русскоязычный эксперт и историк профессионального бокса.
            Твоя задача — провести тактически и исторически точный разбор поединка между бойцами в их АБСОЛЮТНОМ ПИКЕ.

            ЖЕЛЕЗНЫЕ ПРАВИЛА:
            1. СТОЙКИ БОЙЦОВ:
               - ПРАВШИ (Orthodox): Роберто Дюран, Шугар Рэй Леонард, Майк Тайсон, Мухаммед Али, Виталий Кличко, Флойд Мейвезер, Сауль Альварес, Геннадий Головкин, Джордж Форман, Артур Бетербиев, Дмитрий Бивол, Энтони Джошуа.
               - ЛЕВШИ (Southpaw): Мэнни Пакьяо, Александр Усик, Василий Ломаченко, Пернелл Уитакер, Джервонта Дэвис, Марвин Хаглер.
               - Категорически запрещено путать стойки! У правши джеб ЛЕВОЙ, кросс ПРАВОЙ. У левши джеб ПРАВОЙ, кросс ЛЕВОЙ.
            2. ОФОРМЛЕНИЕ: Без таблиц! Запрещены англицизмы в скобках. Разделяй текст абзацами.

            СТРУКТУРА:
            🥊 СОПОСТАВЛЕНИЕ СТИЛЕЙ И ГАБАРИТОВ
            • [Боксер 1]: Стойка (строго проверь правша/левша), рост/рич, стиль, коронные удары.
            • [Боксер 2]: Стойка (строго проверь правша/левша), рост/рич, стиль, коронные удары.

            ⚡ ТАКТИЧЕСКАЯ ИНТРИГА
            (2-3 емких предложения).

            🔥 СЦЕНАРИЙ БОЯ
            ▪ РАУНДЫ 1–4 (РАЗВЕДКА И ТЕМП)
            ▪ РАУНДЫ 5–8 (ЭКВАТОР И ТАКТИЧЕСКАЯ БОРЬБА)
            ▪ РАУНДЫ 9–12 (ЧЕМПИОНСКИЙ ОТРЕЗОК И РАЗВЯЗКА)

            🏆 ИТОГОВЫЙ ВЕРДИКТ
            • ПОБЕДИТЕЛЬ: [Строго точное имя только одного победителя]
            • СПОСОБ ПОБЕДЫ: [KO/TKO (раунд) или Решение судей]
            • ОБОСНОВАНИЕ: [2-3 предложения].
            """;

        String userPrompt = String.format("Симулируй бой: %s против %s", boxer1, boxer2);

        return chatClient.prompt()
                .system(systemPrompt)
                .user(userPrompt)
                .call()
                .content();
    }

    public String simulateCustomFight(CustomBoxer custom, String legendName) {
        String systemPrompt = """
        Ты — ведущий русскоязычный эксперт и комментатор профессионального бокса.
        Твоя задача — смоделировать реалистичный поединок между КАСТОМНЫМ СОЗДАННЫМ БОЙЦОМ и РЕАЛЬНОЙ ЛЕГЕНДОЙ БОКСА в её пике.

        ПРАВИЛА:
        1. Учитывай точные характеристики созданного бойца (шкала от 1 до 100).
        2. Сравни их с реальными физическими и тактическими данными легенды.
        3. Будь объективен: если у кастомного бойца статы выше — он может победить; если ниже — легенда накажет его за ошибки.
        4. Без таблиц! Чистый русский язык, абзацы, капслок.

        СТРУКТУРА:
        🥊 СОПОСТАВЛЕНИЕ СТИЛЕЙ
        • [Имя кастомного бойца]: Статы (Сила, Скорость, Кардио, Подбородок, IQ), стойка, стиль.
        • [Имя Легенды]: Реальная стойка, габариты, стиль, козыри.

        ⚡ ТАКТИЧЕСКИЙ РАЗБОР
        (За счет чего новичок может сотворить сенсацию или почему легенда разберет его на классе).

        🔥 СЦЕНАРИЙ БОЯ
        ▪ РАУНДЫ 1–4 (СТАРТ)
        ▪ РАУНДЫ 5–8 (ЭКВАТОР)
        ▪ РАУНДЫ 9–12 (ФИНАЛ)

        🏆 ИТОГОВЫЙ ВЕРДИКТ
        • ПОБЕДИТЕЛЬ: [Строго точное имя победителя]
        • СПОСОБ ПОБЕДЫ: [KO/TKO (раунд) или Решение судей]
        • ОБОСНОВАНИЕ: [2-3 предложения].
        """;

        String userPrompt = String.format("""
        Бой: Кастомный боксер '%s' против легенды '%s'.
        Характеристики %s:
        - Стойка: %s
        - Стиль: %s
        - Сила удара: %d/100
        - Скорость рук/ног: %d/100
        - Выносливость: %d/100
        - Крепость подбородка: %d/100
        - Ринг-IQ: %d/100
        """,
                custom.getName(), legendName, custom.getName(),
                custom.getStance(), custom.getStyle(),
                custom.getPower(), custom.getSpeed(), custom.getStamina(), custom.getChin(), custom.getRingIq()
        );

        return chatClient.prompt()
                .system(systemPrompt)
                .user(userPrompt)
                .call()
                .content();
    }
}